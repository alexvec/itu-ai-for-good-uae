// R7. Tables for the technical report, generated from the same data files the app runs on.
import evidenceJson from "../data/evidence-map.json" with { type: "json" };
import scenario from "../data/scenarios/primary.json" with { type: "json" };
import { chunkById, chunks, chunksForDoc, docById, documents, NOT_INGESTED } from "./data.ts";
import { allControlResults, allOutcomes, dimensionName, dimensions, emptyState, nodeMapping, rules, runStep, type Citation } from "./engine.ts";
import { NO_GLOBAL_EXAMPLE, NOT_ADDRESSED, PIPELINE, type NodeId } from "./types.ts";

export interface EvidenceRow { node: NodeId; use_case: string; dimension_id: number; why_dimension: string; citation: Citation | null }
export interface NonDataRow { item: string; node: NodeId; dimension_id: number; note: string; citation: Citation }
const ev = evidenceJson as unknown as { use_case: string; pipeline: EvidenceRow[]; supporting: EvidenceRow[]; non_data: NonDataRow[] };

export const useCase = ev.use_case;
export const pipelineRows = PIPELINE.map((n) => ev.pipeline.find((r) => r.node === n)!);
export const supportingRows = ev.supporting;
export const nonDataRows = ev.non_data;

const clean = (s: string) => s.replace(/\s+/g, " ").trim().replace(/\|/g, "\\|");
const cite = (c: Citation | null) => {
  if (!c) return NOT_ADDRESSED;
  const d = docById.get(c.doc_id)!;
  return `${d.short}, PDF p. ${c.page}, ${c.section}, chunk \`${c.chunk_id}\`: "${clean(c.quote)}"${d.analogy_note ? " (government-services guidance, applied by analogy)" : ""}`;
};
const dim = (id: number, node: NodeId) => `D${id} ${dimensionName(id)} (factor: ${nodeMapping.node_to_factors[node]})`;

/** One observed pass of the scenario. Observations of behaviour, not scores. */
export function observedRun() {
  let state = emptyState();
  return scenario.events.map((e) => {
    const r = runStep(e.text, state);
    state = r.state;
    return { event: e, result: r };
  });
}

export function evidenceMarkdown(): string {
  const o: string[] = [];
  o.push("# Report evidence", "", "Generated by `npm run evidence` from the data files the app reads. Scenario is synthetic. No accuracy number is reported.", "");
  o.push("## Limits of the knowledge base", "");
  o.push("The KB has no binding telecom sector law. The four documents are a strategy, a charter, ethics guidance and government-services guidance. Where the guideline is used it is applied by analogy.", "");
  for (const n of NOT_INGESTED) o.push(`- ${n.name}: ${n.note}`);
  o.push("", `"${NOT_ADDRESSED}" describes these four files only. It does not say what UAE law requires.`, "");
  o.push("## Use case", "", ev.use_case, "");
  o.push("## Y.3172 node mapping", "", "| Node | Use case | Readiness dimension | Policy document |", "|---|---|---|---|");
  for (const r of pipelineRows) o.push(`| ${r.node} | ${clean(r.use_case)} | ${dim(r.dimension_id, r.node)} | ${cite(r.citation)} |`);
  o.push("", "Supporting components in Y.3172:", "", "| Node | Use case | Readiness dimension | Policy document |", "|---|---|---|---|");
  for (const r of ev.supporting) o.push(`| ${r.node} | ${clean(r.use_case)} | ${dim(r.dimension_id, r.node)} | ${cite(r.citation)} |`);
  o.push("", "## Readiness items beyond data and models", "", "| Item | Node | Readiness dimension | Policy document | Note |", "|---|---|---|---|---|");
  for (const r of ev.non_data) o.push(`| ${r.item} | ${r.node} | ${dim(r.dimension_id, r.node)} | ${cite(r.citation)} | ${clean(r.note)} |`);
  o.push("", "## Local policy mapping: pre-agreed rules", "", "These rules were drafted in this build and have not been reviewed by a lawyer.", "", "| Rule | Action | Nodes | Dimension | Citation |", "|---|---|---|---|---|");
  for (const r of rules) o.push(`| ${r.id} | ${clean(r.action)} | ${r.nodes.join(", ")} | D${r.dimension_id} ${dimensionName(r.dimension_id)} | ${cite(r.citation)} |`);
  o.push("", "## Template outcomes against the text", "", "| Template example | Status | What the text supports | What it does not |", "|---|---|---|---|");
  for (const t of allOutcomes()) o.push(`| ${t.template_outcome} | ${t.status} | ${clean(t.supported) || "nothing stated"} | ${clean(t.unsupported)} |`);
  o.push("", "## Evaluation scenario: observed behaviour", "", `${scenario.title}. ${scenario.disclaimer}`, "", "| # | Beat | Expected nodes (by design) | Observed nodes | Rules fired | Decided actions | Questions not addressed |", "|---|---|---|---|---|---|---|");
  for (const { event: e, result: r } of observedRun()) {
    o.push(`| ${e.release_order} | ${e.beat} | ${e.author_nodes.join(", ")} | ${r.nodes.join(", ")} | ${r.rule_findings.map((f) => f.rule_id).join(", ") || "none"} | ${r.decision?.actions.map((a) => a.rule_id).join(", ") || "none"} | ${r.controls.filter((c) => !c.addressed).map((c) => c.id).join(", ") || "none"} |`);
  }
  o.push("", "## Candidate gaps", "", "All candidate, needs human legal review. Absence here is absence from these four files.", "", "| Gap | Question | Nodes | Dimension | Status | Nearest text | Global example |", "|---|---|---|---|---|---|---|");
  for (const c of allControlResults().filter((x) => !x.addressed)) {
    const n = c.nearest ? `${c.nearest.document}, PDF p. ${c.nearest.page}, \`${c.nearest.chunk_id}\`: "${clean(c.nearest.quote)}"${c.nearest.analogy_note ? " (by analogy)" : ""}` : "none retrieved";
    o.push(`| ${c.id} | ${clean(c.question)} | ${c.nodes.join(", ")} | D${c.dimension_id} ${c.dimension} | ${c.status}; ${c.review_flag} | ${n} | ${NO_GLOBAL_EXAMPLE} |`);
  }
  o.push("", "## Sources", "", "| Document | Type | Chunks | SHA-256 |", "|---|---|---|---|");
  for (const d of documents) o.push(`| ${d.title} | ${d.instrument_type} | ${chunksForDoc(d.id).length} | \`${chunksForDoc(d.id)[0].sha256}\` |`);
  o.push("", `Total chunks: ${chunks.length}. OCR-derived chunks: ${chunks.filter((c) => c.extraction === "ocr").length}.`, "");
  o.push(`Framework: ${dimensions.length} Readiness dimensions and the node mapping come from ${nodeMapping.source} (${nodeMapping.license}).`, "");
  return o.join("\n");
}

export { chunkById };
